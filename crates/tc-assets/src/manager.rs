use sha2::{Digest, Sha256};
use std::fs;
use std::path::{Path, PathBuf};
use tc_core::{Asset, AssetKind, Result, TcError};

pub struct AssetManager {
    project_media_dir: PathBuf,
}

impl AssetManager {
    pub fn new(project_media_dir: impl AsRef<Path>) -> Self {
        let p = project_media_dir.as_ref().to_path_buf();
        let _ = fs::create_dir_all(&p);
        Self {
            project_media_dir: p,
        }
    }

    pub fn compute_sha256(data: &[u8]) -> String {
        let mut hasher = Sha256::new();
        hasher.update(data);
        format!("{:x}", hasher.finalize())
    }

    pub fn validate_license(license: &str, attribution: Option<&str>) -> Result<()> {
        let lic_upper = license.trim().to_uppercase();
        match lic_upper.as_str() {
            "CC0" | "CC0-1.0" | "PD" | "PUBLIC DOMAIN" | "USER-OWNED" => Ok(()),
            "CC-BY" | "CC-BY-4.0" => {
                if attribution.is_none() || attribution.unwrap().trim().is_empty() {
                    Err(TcError::AssetError(
                        "CC-BY requires non-empty attribution".into(),
                    ))
                } else {
                    Ok(())
                }
            }
            _ => Err(TcError::AssetError(format!(
                "License '{}' is not approved. Must be CC0, CC-BY, PD, or USER-OWNED",
                license
            ))),
        }
    }

    pub fn import_asset(
        &self,
        src_path: impl AsRef<Path>,
        kind: AssetKind,
        license: &str,
        attribution: Option<&str>,
        source_url: Option<&str>,
    ) -> Result<Asset> {
        Self::validate_license(license, attribution)?;

        let bytes = fs::read(&src_path).map_err(TcError::Io)?;
        let sha256 = Self::compute_sha256(&bytes);

        let file_name = src_path
            .as_ref()
            .file_name()
            .and_then(|n| n.to_str())
            .unwrap_or("asset.dat");

        let dest_filename = format!("{}_{}", &sha256[0..12], file_name);
        let dest_path = self.project_media_dir.join(&dest_filename);

        fs::write(&dest_path, &bytes).map_err(TcError::Io)?;

        let asset_id = format!("asset_{}", &sha256[0..8]);
        Ok(Asset {
            id: asset_id,
            kind,
            path: dest_filename,
            sha256,
            license: license.to_string(),
            attribution: attribution.map(|s| s.to_string()),
            source_url: source_url.map(|s| s.to_string()),
            duration_ms: None,
            width: None,
            height: None,
        })
    }

    pub fn generate_credits_file(assets: &[Asset], dest_path: impl AsRef<Path>) -> Result<()> {
        let mut lines = Vec::new();
        lines.push("=== CREDITS & ATTRIBUTIONS ===".to_string());
        lines.push("Generated by Antares ThreadClip Studio\n".to_string());

        for asset in assets {
            lines.push(format!("Asset: {}", asset.path));
            lines.push(format!("  License: {}", asset.license));
            if let Some(ref attr) = asset.attribution {
                lines.push(format!("  Attribution: {}", attr));
            }
            if let Some(ref url) = asset.source_url {
                lines.push(format!("  Source: {}", url));
            }
            lines.push(String::new());
        }

        fs::write(dest_path, lines.join("\n")).map_err(TcError::Io)?;
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_license_validation() {
        assert!(AssetManager::validate_license("CC0-1.0", None).is_ok());
        assert!(AssetManager::validate_license("USER-OWNED", None).is_ok());

        // CC-BY without attribution must fail
        assert!(AssetManager::validate_license("CC-BY-4.0", None).is_err());
        assert!(AssetManager::validate_license("CC-BY-4.0", Some("By John")).is_ok());

        // Unknown license must fail
        assert!(AssetManager::validate_license("Commercial-Unknown", None).is_err());
    }
}
